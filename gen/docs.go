// Package gen contains functions to generate documentation and framework-specific boilerplate code
// from a valid OpenCLI specification document.
//
// Given a [spec.Document], gen can produce:
//
//  1. Documentation — Call [Docs] to generate Markdown (or other formats) suitable
//     for publishing CLI reference documentation.
//
//  2. CLI code — Call [CLI] with a target [CLIFramework] to generate boilerplate
//     code for one of the supported frameworks:
//
//     • [CobraFramework] — github.com/spf13/cobra (Go)
//     • [UrfaveCliFramework] — github.com/urfave/cli/v3 (Go)
//     • [YargsFramework] — yargs (Node.js)
//
// Generated code is returned as a map of relative file paths to their contents,
// ready to be written to disk. All files belong to a single gencli package so no
// cross-package import paths are required.
//
// Both [CLI] and [Docs] support functional options for configuring output format,
// framework, badges, footers, and other generation parameters.
package gen

import (
	"errors"
	"fmt"

	"github.com/bcdxn/opencli/spec"
)

// Docs generates documentation based on the given OpenCLI document.
// It delegates to format-specific generators:
//
// - [Markdown] → genDocsMarkdown (docs_md.go)
// - [HTML_PAGE], [HTML_EMBED] → genDocsHTML (docs_html.go)
func Docs(doc *spec.Document, options ...GenDocsOption) ([]byte, error) {
	opts := &genDocsOptions{
		Format:        Markdown,
		IncludeBadge:  true,
		IncludeFooter: true,
	}

	for _, option := range options {
		option(opts)
	}

	if !opts.Format.IsValid() {
		return []byte{}, errors.New("invalid documentation format")
	}

	return genDocs(docsTmplData{*opts, doc})
}

/* Functional Options
------------------------------------------------------------------------------------------------- */

// GenDocsOption is a functional option to configure the Docs function.
type GenDocsOption func(*genDocsOptions)

// DocsWithoutFooter option will remove the `generated by OpenCLI` footer appended to the documents by default.
func DocsWithoutFooter() GenDocsOption {
	return func(opts *genDocsOptions) {
		opts.IncludeFooter = false
	}
}

// DocsWithoutBadge option will remove shields.io badge that indicates compliance with the OpenCLI Spec prepended to markdown documents by default.
func DocsWithoutBadge() GenDocsOption {
	return func(opts *genDocsOptions) {
		opts.IncludeBadge = false
	}
}

// DocsWithFormat sets the desired output format of the documentation.
func DocsWithFormat(format DocFormat) GenDocsOption {
	return func(opts *genDocsOptions) {
		opts.Format = format
	}
}

// DocFormat is the output format for generated documentation.
type DocFormat string

const (
	// Markdown generates plain Markdown documentation.
	Markdown DocFormat = "MARKDOWN"
	// HTML_PAGE generates a full standalone HTML page.
	HTML_PAGE DocFormat = "HTML_PAGE"
	// HTML_EMBED generates a JavaScript bundle that can be embedded in an existing page.
	HTML_EMBED DocFormat = "HTML_EMBED"
	// ManPage generates a man page (not yet implemented).
	ManPage DocFormat = "MAN"
)

// IsValid reports whether f is a supported DocFormat.
func (f DocFormat) IsValid() bool {
	switch f {
	case Markdown, HTML_PAGE, HTML_EMBED, ManPage:
		return true
	}
	return false
}

/* Private functions and types
------------------------------------------------------------------------------------------------- */

// genDocsOptions represents the configurable options when generating documentation.
// The options are meant to be configured using the functional options pattern.
type genDocsOptions struct {
	Format        DocFormat
	IncludeBadge  bool
	IncludeFooter bool
}

// docsTmplData represents the data used to render the documentation template.
type docsTmplData struct {
	Opts genDocsOptions
	Doc  *spec.Document
}

// genDocs is a helper/orchestrator function that dispatches to the format-appropriate generator.
func genDocs(data docsTmplData) ([]byte, error) {
	switch data.Opts.Format {
	case Markdown:
		return genDocsMarkdown(data)
	case HTML_PAGE, HTML_EMBED:
		return genDocsHTML(data)
	case ManPage:
		return genDocsMan(data)
	}

	return []byte{}, fmt.Errorf("unsupported documentation format: %s", data.Opts.Format)
}
